// src/core/layout/types.ts
// ------------------------------------------------------------
//  Layout 相關的最小通用型別
//  - Margin：留白設定（SVG/Canvas 都會用到）
//  - PlotOffset：在可用 inner 區域內的偏移（置中/多圖表排版）
//
//  SRP：這個檔案只放「型別」，不放常數/邏輯。
// ------------------------------------------------------------

// ------------------------------------------------------------
// Margin：SVG/畫布留白設定
// ------------------------------------------------------------
export type Margin = {
  top: number;
  right: number;
  bottom: number;
  left: number;
};

// ------------------------------------------------------------
// PlotOffset：plot 區在 inner 可用空間內的置中位移
// ------------------------------------------------------------
export type PlotOffset = {
  x: number;
  y: number;
};
